"""
RLBench Dataset implementation.

This module contains the RLBenchDataset class for loading RLBench demonstration data
in HDF5 format generated by benchmark/rlbench/generate_dataset.py.

Supports multiple control spaces:
- 'ee': End-effector pose (7D) + gripper (1D) = 8D action/state
- 'joint': Joint positions (7D) + gripper (1D) = 8D action/state  
- 'joint_vel': Joint velocities (7D) + gripper (1D) = 8D action/state
"""

import numpy as np
import cv2
import h5py
import os
import yaml
from .base import EpisodicDataset


class RLBenchDataset(EpisodicDataset):
    """
    Dataset class for RLBench demonstration data.
    
    This class handles loading and processing of RLBench datasets stored in HDF5 format.
    The data is generated using benchmark/rlbench/generate_dataset.py.
    
    Args:
        dataset_path_list: List containing dataset directory path or list of HDF5 files
        camera_names: List of camera names to use (e.g., ['front', 'wrist'])
        chunk_size: Number of timesteps per action chunk
        ctrl_space: Control space type ('ee', 'joint', 'joint_vel')
        ctrl_type: Control type ('abs', 'delta')
        image_size: Target image size (height, width)
        preload_data: Whether to preload all data into memory
    """
    
    # Camera name mapping from config names to HDF5 dataset names
    CAMERA_MAPPING = {
        'front': 'front',
        'wrist': 'wrist',
        'left_shoulder': 'left_shoulder',
        'right_shoulder': 'right_shoulder',
        'overhead': 'overhead',
        # Also support direct names
        'front_rgb': 'front',
        'wrist_rgb': 'wrist',
    }
    
    def __init__(self, dataset_path_list, camera_names=['front', 'wrist'],
                 chunk_size=16, ctrl_space='joint', ctrl_type='abs',
                 image_size=(128, 128), preload_data=False):
        # Ensure dataset_path_list is a list
        if isinstance(dataset_path_list, str):
            dataset_path_list = [dataset_path_list]
            
        # Store ctrl_space before calling parent init (which calls initialize)
        self._ctrl_space_init = ctrl_space
        
        super().__init__(
            dataset_path_list=dataset_path_list,
            camera_names=camera_names,
            chunk_size=chunk_size,
            ctrl_space=ctrl_space,
            ctrl_type=ctrl_type,
            image_size=image_size,
            preload_data=preload_data
        )
        
        # Load metadata if available
        self._load_metadata()
    
    def _load_metadata(self):
        """Load dataset metadata from metadata.yaml if available."""
        metadata_path = os.path.join(self.dataset_dir, 'metadata.yaml')
        self.metadata = {}
        if os.path.exists(metadata_path):
            with open(metadata_path, 'r') as f:
                self.metadata = yaml.safe_load(f) or {}
    
    def get_language_instruction(self):
        """
        Get language instruction for the dataset.
        
        Returns:
            String containing the primary language instruction
        """
        # Try to get from metadata
        if self.metadata and 'language_instructions' in self.metadata:
            instructions = self.metadata['language_instructions']
            if isinstance(instructions, list) and len(instructions) > 0:
                return instructions[0]
        
        # Try to get from first episode
        if len(self.dataset_path_list) > 0:
            try:
                with h5py.File(self.dataset_path_list[0], 'r') as f:
                    if 'language_instruction' in f:
                        lang = f['language_instruction'][()]
                        if isinstance(lang, bytes):
                            return lang.decode('utf-8')
                        elif isinstance(lang, np.ndarray) and len(lang) > 0:
                            item = lang[0]
                            return item.decode('utf-8') if isinstance(item, bytes) else str(item)
                        return str(lang)
                    elif 'language' in f.attrs:
                        return f.attrs['language']
            except Exception:
                pass
        
        # Default instruction based on task
        task_name = self.metadata.get('task', 'unknown')
        return f"Complete the {task_name} task."
    
    def _get_state_action_from_obs(self, root, start_ts, end_ts=None):
        """
        Extract state and action based on ctrl_space setting.
        
        Args:
            root: HDF5 file or loaded data dict
            start_ts: Starting timestep
            end_ts: Ending timestep (optional, for chunk loading)
            
        Returns:
            Tuple of (action, state) numpy arrays
        """
        if end_ts is None:
            end_ts = start_ts + self.chunk_size
        
        # Check if we have pre-computed action/state
        if '/action' in root and '/state' in root:
            action = root['/action'][start_ts:end_ts]
            state = root['/state'][start_ts]
            
            # Verify ctrl_space matches or recompute
            stored_ctrl_space = None
            if hasattr(root, 'attrs') and 'ctrl_space' in root.attrs:
                stored_ctrl_space = root.attrs['ctrl_space']
            elif isinstance(root, dict):
                # For preloaded data, we trust the stored action/state
                pass
            
            if stored_ctrl_space == self.ctrl_space or stored_ctrl_space is None:
                return action, state
        
        # Recompute action/state based on ctrl_space
        obs_prefix = '/observations/'
        
        joint_positions = root[f'{obs_prefix}joint_positions'][start_ts:end_ts]
        joint_velocities = root[f'{obs_prefix}joint_velocities'][start_ts:end_ts]
        gripper_pose = root[f'{obs_prefix}gripper_pose'][start_ts:end_ts]
        gripper_open = root[f'{obs_prefix}gripper_open'][start_ts:end_ts]
        
        if self.ctrl_space == 'ee':
            action = np.concatenate([gripper_pose, gripper_open], axis=-1)
            state = action[0]
        elif self.ctrl_space == 'joint_vel':
            action = np.concatenate([joint_velocities, gripper_open], axis=-1)
            state = np.concatenate([joint_positions[0], gripper_open[0]], axis=-1)
        else:  # 'joint'
            action = np.concatenate([joint_positions, gripper_open], axis=-1)
            state = action[0]
        
        return action, state
    
    def load_onestep_from_episode(self, dataset_path, start_ts=None):
        """
        Load one-step data at start_ts from the episode specified by dataset_path.
        
        Args:
            dataset_path: Path to the HDF5 file
            start_ts: Starting timestep
            
        Returns:
            Dictionary containing action, image, state, and language_instruction
        """
        if self.loaded_data is not None:
            root = self.loaded_data[dataset_path]
            is_preloaded = True
        else:
            root = h5py.File(dataset_path, 'r')
            is_preloaded = False
        
        try:
            # Load text
            raw_lang = self.get_language_instruction()
            
            # Load action & state
            action, state = self._get_state_action_from_obs(root, start_ts)
            
            # Handle delta control type
            if self.ctrl_type == 'delta':
                # Get states for the chunk to compute deltas
                _, states_chunk = self._get_state_action_from_obs(root, start_ts, start_ts + self.chunk_size)
                if len(action) > 0:
                    # Compute delta: action[t] = state[t+1] - state[t]
                    # For simplicity, use action - current_state
                    state_expanded = np.tile(state, (len(action), 1))
                    action = action - state_expanded
            
            # Load images
            image_dict = {}
            for cam_name in self.camera_names:
                # Map camera name to HDF5 key
                hdf5_cam_name = self.CAMERA_MAPPING.get(cam_name, cam_name)
                key = f'/observations/images/{hdf5_cam_name}'
                
                if key in root:
                    img = root[key][start_ts]
                    # Resize if needed
                    if self.image_size is not None:
                        if img.shape[0] != self.image_size[0] or img.shape[1] != self.image_size[1]:
                            img = cv2.resize(img, (self.image_size[1], self.image_size[0]))
                    image_dict[cam_name] = img
            
            return {
                'action': action,
                'image': image_dict,
                'state': state,
                'language_instruction': raw_lang,
                'reasoning': '',
            }
        finally:
            if not is_preloaded:
                root.close()
    
    def load_feat_from_episode(self, dataset_path, feats=[]):
        """
        Load all steps data from the episode specified by dataset_path.
        
        Args:
            dataset_path: Path to the HDF5 file
            feats: List of features to load (empty = load all)
            
        Returns:
            Dictionary containing the loaded data
        """
        data_dict = {}
        if isinstance(feats, str):
            feats = [feats]
        
        with h5py.File(dataset_path, 'r') as root:
            episode_len = root['/episode_len'][0] if '/episode_len' in root else root['/action'].shape[0]
            
            if 'language_instruction' in feats or len(feats) == 0:
                data_dict['language_instruction'] = self.get_language_instruction()
            
            if 'state' in feats or 'action' in feats or len(feats) == 0:
                # Load full episode action and state
                obs_prefix = '/observations/'
                
                joint_positions = root[f'{obs_prefix}joint_positions'][:]
                joint_velocities = root[f'{obs_prefix}joint_velocities'][:]
                gripper_pose = root[f'{obs_prefix}gripper_pose'][:]
                gripper_open = root[f'{obs_prefix}gripper_open'][:]
                
                if self.ctrl_space == 'ee':
                    action = np.concatenate([gripper_pose, gripper_open], axis=-1)
                    state = action.copy()
                elif self.ctrl_space == 'joint_vel':
                    action = np.concatenate([joint_velocities, gripper_open], axis=-1)
                    state = np.concatenate([joint_positions, gripper_open], axis=-1)
                else:  # 'joint'
                    action = np.concatenate([joint_positions, gripper_open], axis=-1)
                    state = action.copy()
                
                if self.ctrl_type == 'delta':
                    # Compute delta actions
                    action_delta = np.zeros_like(action)
                    action_delta[:-1] = action[1:] - action[:-1]
                    action = action_delta
                
                if 'action' in feats or len(feats) == 0:
                    data_dict['action'] = action
                if 'state' in feats or len(feats) == 0:
                    data_dict['state'] = state
            
            if 'image' in feats or len(feats) == 0:
                image_dict = {}
                for cam_name in self.camera_names:
                    hdf5_cam_name = self.CAMERA_MAPPING.get(cam_name, cam_name)
                    key = f'/observations/images/{hdf5_cam_name}'
                    
                    if key in root:
                        all_images = root[key][:]
                        if self.image_size is not None:
                            resized = []
                            for img in all_images:
                                if img.shape[0] != self.image_size[0] or img.shape[1] != self.image_size[1]:
                                    img = cv2.resize(img, (self.image_size[1], self.image_size[0]))
                                resized.append(img)
                            image_dict[cam_name] = resized
                        else:
                            image_dict[cam_name] = list(all_images)
                
                data_dict['image'] = image_dict
        
        return data_dict
    
    def get_episode_len(self):
        """
        Get the length of each episode in the dataset.
        
        For RLBench datasets, we always have /episode_len stored in HDF5 files,
        so we can directly read it for better performance.
        
        Returns:
            List of episode lengths
        """
        if self.loaded_data is not None:
            # Preloaded data case
            all_episode_len = []
            for dataset_path in self.dataset_path_list:
                if dataset_path in self.loaded_data:
                    data = self.loaded_data[dataset_path]
                    if '/episode_len' in data:
                        elen = data['/episode_len'][0].astype(np.int32)
                    elif '/action' in data:
                        elen = data['/action'].shape[0]
                    elif '/observations/joint_positions' in data:
                        elen = data['/observations/joint_positions'].shape[0]
                    else:
                        raise ValueError(f"Could not determine episode length for {dataset_path}")
                    all_episode_len.append(elen)
                else:
                    # Fallback: try to load from file
                    try:
                        with h5py.File(dataset_path, 'r') as root:
                            elen = root['/episode_len'][0].astype(np.int32) if '/episode_len' in root else root['/action'].shape[0]
                            all_episode_len.append(elen)
                    except Exception as e:
                        raise RuntimeError(f'Error loading {dataset_path} in get_episode_len: {e}')
        else:
            # Not preloaded: read from files
            all_episode_len = []
            for dataset_path in self.dataset_path_list:
                try:
                    with h5py.File(dataset_path, 'r') as root:
                        # RLBench datasets always have /episode_len
                        if '/episode_len' in root:
                            elen = root['/episode_len'][0].astype(np.int32)
                        elif '/action' in root:
                            elen = root['/action'].shape[0]
                        elif '/observations/joint_positions' in root:
                            elen = root['/observations/joint_positions'].shape[0]
                        else:
                            raise ValueError(f"Could not determine episode length for {dataset_path}")
                        all_episode_len.append(elen)
                except Exception as e:
                    raise RuntimeError(f'Error loading {dataset_path} in get_episode_len: {e}')
        
        return all_episode_len
    
